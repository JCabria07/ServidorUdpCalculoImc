    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        try {
            String ipLocal = InetAddress.getLocalHost().getHostAddress();
            campoIP.setText(ipLocal);
        } catch (UnknownHostException ex) {
            campoIP.setText("127.0.0.1");
        }
    }//GEN-LAST:event_formWindowOpened

    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        if (gestionarServidorPort == null) {
            JOptionPane.showMessageDialog(this, "El servicio del servidor no está inicializado.");
            return;
        }

        if (btnIniciar.getText().equalsIgnoreCase("INICIAR")) {
            if (campoPuerto.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe ingresar un puerto.");
                return;
            }

            int puerto;
            try {
                puerto = Integer.parseInt(campoPuerto.getText().trim());
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El puerto debe ser numérico.");
                return;
            }

            try {
                gestionarServidorPort.iniciarServidor(puerto);
            } catch (ServidorRedException ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage());
            }

        } else if (btnIniciar.getText().equalsIgnoreCase("DETENER")) {
            gestionarServidorPort.detenerServidor();
        }
    }//GEN-LAST:event_btnIniciarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        cajaLog.setText("");
    }//GEN-LAST:event_btnLimpiarActionPerformed

    @Override
    public void onEvento(final EventoServidor evento) {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                cajaLog.append(evento.getFormatoLog() + "\n");
                cajaLog.setCaretPosition(cajaLog.getDocument().getLength());
            }
        });
    }

    @Override
    public void onCambioEstado(final EstadoServidor estado, final int puerto) {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                if (estado == EstadoServidor.ESCUCHANDO) {
                    btnIniciar.setText("DETENER");
                    btnIniciar.setForeground(Color.RED);
                    txtEstado.setText("ONLINE");
                    txtEstado.setForeground(Color.GREEN);
                    campoPuerto.setEditable(false);
                } else {
                    btnIniciar.setText("INICIAR");
                    btnIniciar.setForeground(new Color(51, 153, 0));
                    txtEstado.setText("OFF LINE");
                    txtEstado.setForeground(Color.RED);
                    campoPuerto.setEditable(true);
                }
            }
        });
    }

